// Package testkit builds the fakes this project's tests run against: a Codex CLI
// that is a bash script, an in-memory Telegram, and a workspace that looks like a
// Git repository.
//
// Nothing here touches the network, a real bot token, or a real Codex account.
// The fake Codex records the exact argv, cwd and environment of every
// invocation, which is what lets the tests assert on the real command line
// instead of on a reconstruction of it.
