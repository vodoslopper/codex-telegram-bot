// Alive reports whether a pid still exists.
//
// Signal 0 delivers nothing and only checks existence, which is exactly the
// question a process-group test needs to answer.
func Alive(pid int) bool {
	if pid <= 0 {
		return false
	}
	proc, err := os.FindProcess(pid)
	if err != nil {
		return false
	}
	return proc.Signal(syscall.Signal(0)) == nil
}

// --- JSONL builders --------------------------------------------------------

// Events builds the JSONL stream Codex produces for a successful turn, matching
// the shape published in the Codex non-interactive-mode documentation and
// observed from codex-cli 0.156.1.
func Events(threadID, reply string) string {
	return strings.Join([]string{
		`{"type":"thread.started","thread_id":` + jsonQuote(threadID) + `}`,
		`{"type":"turn.started"}`,
		`{"type":"item.started","item":{"id":"item_1","type":"command_execution","command":"ls","status":"in_progress"}}`,
		`{"type":"item.completed","item":{"id":"item_1","type":"command_execution","output":"README.md","status":"completed"}}`,
		`{"type":"item.completed","item":{"id":"item_2","type":"agent_message","text":` + jsonQuote(reply) + `}}`,
		`{"type":"turn.completed","usage":{"input_tokens":100,"cached_input_tokens":80,"output_tokens":20,"reasoning_output_tokens":0}}`,
	}, "\n") + "\n"
}

// Lines joins raw JSONL lines.
func Lines(lines ...string) string { return strings.Join(lines, "\n") + "\n" }

// UUID is a syntactically valid thread id for tests.
func UUID(seed int) string {
	return fmt.Sprintf("0199a213-81c0-7800-8aa1-%012d", seed)
}

func jsonQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// shQuote wraps s in single quotes for a shell script body.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// --- fake telegram ---------------------------------------------------------

// Sent is one message the bot delivered.
type Sent struct {
	ChatID   int64
	ThreadID int64
	Text     string
	Document string
	Data     []byte
}

// FakeTelegram is an in-memory Bot API.
//
// It records everything sent and hands out a scripted queue of updates, so a
// test can assert on the exact messages a user would have seen without a token,
// a network, or a chat.
type FakeTelegram struct {
	mu       sync.Mutex
	sent     []Sent
	actions  []string
	updates  []telegram.Update
	files    map[string][]byte
	nextID   int64
	me       telegram.User
	webhook  telegram.WebhookInfo
	sendErr  error
	pollErr  error
	pollWait chan struct{}
}

// NewFakeTelegram builds a fake with a default bot identity.
func NewFakeTelegram() *FakeTelegram {
	return &FakeTelegram{
		nextID:  1000,
		files:   make(map[string][]byte),
		me:      telegram.User{ID: 42, FirstName: "Codex", Username: "codex_test_bot"},
		webhook: telegram.WebhookInfo{URL: "https://example.invalid/hook", PendingUpdateCount: 3},
	}
}

// SetFile makes a Telegram file id downloadable by the fake.
func (f *FakeTelegram) SetFile(id string, data []byte) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.files[id] = append([]byte(nil), data...)
}

func (f *FakeTelegram) DownloadFile(_ context.Context, fileID string) ([]byte, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	data, ok := f.files[fileID]
	if !ok {
		return nil, fmt.Errorf("fake Telegram: unknown file %q", fileID)
	}
	return append([]byte(nil), data...), nil
}

// Username is the bot username the fake reports from getMe.
func (f *FakeTelegram) Username() string { return f.me.Username }

// SetSendError makes every sendMessage fail with err.
func (f *FakeTelegram) SetSendError(err error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.sendErr = err
}

// SetPollError makes every getUpdates fail with err.
func (f *FakeTelegram) SetPollError(err error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.pollErr = err
}

// QueueUpdates appends updates to be returned by the next getUpdates calls.
func (f *FakeTelegram) QueueUpdates(u ...telegram.Update) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.updates = append(f.updates, u...)
}

// Sent returns every message delivered so far, in order.
func (f *FakeTelegram) Sent() []Sent {
	f.mu.Lock()
	defer f.mu.Unlock()
	out := make([]Sent, len(f.sent))
	copy(out, f.sent)
	return out
}

// LastText returns the text of the most recent message, or "" when none was sent.
func (f *FakeTelegram) LastText() string {
	f.mu.Lock()
	defer f.mu.Unlock()
	if len(f.sent) == 0 {
		return ""
	}
	return f.sent[len(f.sent)-1].Text
}

// AllText joins every delivered message with a newline, which is what a test
// asserting on a split reply wants.
func (f *FakeTelegram) AllText() string {
	f.mu.Lock()
	defer f.mu.Unlock()
	parts := make([]string, 0, len(f.sent))
	for _, s := range f.sent {
		parts = append(parts, s.Text)
	}
	return strings.Join(parts, "\n")
}

// Actions returns the chat actions requested, e.g. "typing".
func (f *FakeTelegram) Actions() []string {
	f.mu.Lock()
	defer f.mu.Unlock()
	out := make([]string, len(f.actions))
	copy(out, f.actions)
	return out
}

// Reset clears the recorded messages.
func (f *FakeTelegram) Reset() {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.sent = nil
	f.actions = nil
}

// SendMessage records a message.
func (f *FakeTelegram) SendMessage(_ context.Context, chatID, threadID int64, text string) (*telegram.SentMessage, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if f.sendErr != nil {
		return nil, f.sendErr
	}
	f.nextID++
	f.sent = append(f.sent, Sent{ChatID: chatID, ThreadID: threadID, Text: text})
	return &telegram.SentMessage{MessageID: f.nextID}, nil
}

func (f *FakeTelegram) SendDocument(_ context.Context, chatID, threadID int64, path string) (*telegram.SentMessage, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	if f.sendErr != nil {
		return nil, f.sendErr
	}
	f.nextID++
	f.sent = append(f.sent, Sent{ChatID: chatID, ThreadID: threadID, Document: filepath.Base(path), Data: data})
	return &telegram.SentMessage{MessageID: f.nextID}, nil
}

// SendChatAction records a typing indicator.
func (f *FakeTelegram) SendChatAction(_ context.Context, _, _ int64, action string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.actions = append(f.actions, action)
	return nil
}

// GetMe returns the fake bot identity.
func (f *FakeTelegram) GetMe(context.Context) (*telegram.User, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	u := f.me
	return &u, nil
}

// GetWebhookInfo returns a webhook so the deletion path is exercised.
func (f *FakeTelegram) GetWebhookInfo(context.Context) (*telegram.WebhookInfo, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	w := f.webhook
	return &w, nil
}

// DeleteWebhook clears the fake webhook.
func (f *FakeTelegram) DeleteWebhook(context.Context, bool) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.webhook = telegram.WebhookInfo{}
	return nil
}

// GetUpdates returns up to limit queued updates and advances nothing else.
func (f *FakeTelegram) GetUpdates(ctx context.Context, offset int64, _ time.Duration, limit int) ([]telegram.Update, error) {
	f.mu.Lock()
	pollErr := f.pollErr
	var out []telegram.Update
	keep := f.updates[:0]
	for _, u := range f.updates {
		if u.UpdateID >= offset && len(out) < limit {
			out = append(out, u)
			continue
		}
		keep = append(keep, u)
	}
	f.updates = keep
	f.mu.Unlock()

	if pollErr != nil {
		return nil, pollErr
	}
	return out, nil
}

// --- update builders -------------------------------------------------------

// MessageUpdate builds a private-chat text message update.
func MessageUpdate(updateID, chatID, userID int64, text string) telegram.Update {
	return telegram.Update{
		UpdateID: updateID,
		Message: &telegram.Message{
			MessageID: updateID,
			Date:      time.Now().Unix(),
			Text:      text,
			From:      &telegram.User{ID: userID, FirstName: "User"},
			Chat:      telegram.Chat{ID: chatID, Type: "private"},
		},
	}
}

// TopicUpdate builds a private-chat text message inside a topic.
func TopicUpdate(updateID, chatID, threadID, userID int64, text string) telegram.Update {
	u := MessageUpdate(updateID, chatID, userID, text)
	u.Message.MessageThreadID = threadID
	return u
}

// GroupUpdate builds a supergroup message update.
func GroupUpdate(updateID, chatID, userID int64, text string) telegram.Update {
	u := MessageUpdate(updateID, chatID, userID, text)
	u.Message.Chat.Type = "supergroup"
	return u
}
