// Workspace returns a temporary directory that passes the bot's "must be a Git
// repository" check.
//
// It creates a bare .git directory rather than running `git init`, so the tests
// do not depend on git being installed or on its configuration.
func Workspace(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, ".git"), 0o755); err != nil {
		t.Fatalf("create a fake .git: %v", err)
	}
	return dir
}

